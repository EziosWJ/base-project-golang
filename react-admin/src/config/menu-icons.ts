function normalizeIconName(icon?: string | null): string {
  return (icon ?? '').trim().replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase().replace(/-/g, '');
}

export function getMenuIcon(icon?: string | null): LucideIcon | undefined {
  const normalized = normalizeIconName(icon);
  if (!normalized) return undefined;
  return MENU_ICON_MAP[normalized];
}
